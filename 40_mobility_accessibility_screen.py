#!/usr/bin/env python
"""
40_mobility_accessibility_screen.py  --  can two new external datasets be used?
===============================================================================

Two datasets were proposed as additions to the paper:

  WorldMove (Yuan et al., Sci Data 2026)
      synthetic half-hourly mobility for >1,600 cities on a 1 km grid,
      generated by a diffusion model from gridded population + POI + commuting
      OD.  Proposal: replace the static population weight with an "ambient" or
      synthetic-population weight.

  15-minute city accessibility (Bruno et al., Nature Cities 2024)
      walking / cycling proximity time (PT) to services, ~10,000 cities.
      Proposal: use accessibility the way built volume per capita was used --
      as a moderator of the thermal-carbon response.

This script answers whether either can be *tested* in this design, using the
same screen that retired R6 (39_lcz_variants.py stage_sweep) and using
EXPOSURE DATA ONLY -- no emissions are touched, so choosing a weight on the
basis of this output cannot bias any reported coefficient.

THE TWO CANDIDATE FAMILIES ARE PROXIED, NOT DOWNLOADED
------------------------------------------------------
Neither dataset needs to be obtained to answer the question, because each
proposal is bounded by a family this study already holds:

  ambient population  ->  w = pop^alpha.
      WorldMove's city totals are generated *from* gridded population, so the
      ambient weight is a smooth monotone function of the residential weight.
      Every monotone transform has within-country Spearman rho = 1 with
      population by construction; what varies is the magnitude reweighting.
      Scanning alpha in [0.7, 1.5] therefore brackets any such weight, and it
      brackets it generously -- alpha = 1.5 is a far more aggressive tilt than
      day-time redistribution could produce.

  accessibility       ->  w = pop * density^k.
      Bruno et al. report that PT is governed by local population density.
      Density is the part of accessibility that survives aggregation to a city
      weight, so pop * density^k spans the family, with k > 0 tilting toward
      dense/walkable cities and k < 0 toward sprawl.

OUTPUT
------
  TS18_external_weight_screen.csv     rho, D share, theta80 for each candidate
  printed verdict per family

theta80 = 2.80 / (t_beta * SD_D/SD_X) is the smallest theta = gamma/beta
detectable at 80 % power; theta = 1 is "the alternative weighting is entirely
correct", so a candidate needs theta80 < 1 to be worth fitting at all.
"""
from __future__ import annotations

import os
from pathlib import Path

import numpy as np
import pandas as pd

BASE = Path(__file__).resolve().parent
RESULTS = Path(os.environ.get("HC_RESULTS_ROOT", BASE / "Results_2019_2022"))
SCHEMES = BASE / "outputs" / "population" / "fua_weight_schemes.parquet"
EVENTS = BASE / "outputs" / "04_events" / "city_events_daily_v2.parquet"
EXPOSURE = BASE / "outputs" / "exposure" / "country_daily_exposure.parquet"
TAB = RESULTS / "SI" / "tables"

COOL, HEAT = "SCDH24", "HDH15"
T_BETA = {"cool": 2.91, "heat": 3.84}          # R3 Power main effects
ALPHAS = [0.7, 0.85, 1.2, 1.5]                 # ambient-population family
KS = [-1.0, -0.5, 0.5, 1.0, 2.0]               # accessibility family


# --------------------------------------------------------------------------
def candidate_weights() -> pd.DataFrame:
    """Build both proxy families on the existing 1,583-city panel."""
    w = pd.read_parquet(SCHEMES)

    # the shared-FUA correction: built_s / built_v hold the FUA total repeated
    # on every shared row, while pop_weight_dedup is already deduplicated.
    w["built_s_ded"] = w.built_s / w.n_share
    pop = w.pop_weight_dedup

    # density: residents per km2 of built surface. This is the quantity Bruno
    # et al. identify as the driver of proximity time.
    dens = pop / (w.built_s_ded / 1e6)
    dens = dens.replace([np.inf, -np.inf], np.nan)
    # normalise to the within-country median so the exponent is scale-free and
    # k means the same thing in every country
    dn = dens / dens.groupby(w.country).transform("median")

    out = w[["city_id", "country", "pop_weight_dedup"]].copy()

    # family A -- ambient / synthetic population: monotone transforms of pop
    for a in ALPHAS:
        out[f"w_popA{a:g}".replace(".", "")] = pop ** a

    # family B -- accessibility: population tilted by density
    for k in KS:
        col = f"w_dens{'m' if k < 0 else ''}{abs(k):g}".replace(".", "")
        out[col] = pop * dn ** k

    # reference points already established in TS17, recomputed here so the new
    # candidates are read on the same scale rather than across two tables
    lcz = pd.read_parquet(BASE / "outputs" / "population" / "fua_lcz_weights.parquet")
    out = out.merge(lcz[["city_id", "w_compact_p4", "w_built_v"]], on="city_id",
                    how="left")
    return out


# --------------------------------------------------------------------------
def screen(w: pd.DataFrame) -> pd.DataFrame:
    wcols = [c for c in w.columns if c.startswith("w_")]

    # 1. rank divergence from population, within country
    rho = {}
    for c in wcols:
        rs = []
        for _, s in w.groupby("country"):
            s2 = s[["pop_weight_dedup", c]].replace(
                [np.inf, -np.inf], np.nan).dropna()
            if len(s2) >= 5 and s2.iloc[:, 0].std() > 0 and s2.iloc[:, 1].std() > 0:
                rs.append(float(s2.corr(method="spearman").iloc[0, 1]))
        rho[c] = float(np.median(rs)) if rs else np.nan

    # 2. tilt variance surviving country x year-month
    ev = pd.read_parquet(EVENTS, columns=["city_id", "date", COOL, HEAT])
    ex = pd.read_parquet(EXPOSURE, columns=["country", "date", "tier"])
    ex["date"] = pd.to_datetime(ex.date)
    ex = ex.drop_duplicates(["country", "date"])

    d = ev.merge(w[["city_id", "country", "pop_weight_dedup"] + wcols],
                 on="city_id", how="inner")
    d = d[d.pop_weight_dedup > 0]

    series = {}
    for wt in ["pop_weight_dedup"] + wcols:
        m = d[d[wt].notna() & (d[wt] > 0)]
        num = pd.DataFrame({"country": m.country, "date": m.date,
                            COOL: m[COOL] * m[wt], HEAT: m[HEAT] * m[wt],
                            "wt": m[wt]})
        g = num.groupby(["country", "date"], sort=False)[[COOL, HEAT, "wt"]].sum()
        for c in (COOL, HEAT):
            series[f"{c}__{wt}"] = g[c] / g["wt"]

    t = pd.DataFrame(series).reset_index()
    t["date"] = pd.to_datetime(t.date)
    t = t.merge(ex, on=["country", "date"], how="left")
    t = t[t.tier.isin(["A", "B"])]
    t["ym"] = t.date.dt.to_period("M").astype(str)

    def resid(col):
        return t[col] - t.groupby(["country", "ym"])[col].transform("mean")

    rows = []
    for side, var in (("cool", COOL), ("heat", HEAT)):
        xr = resid(f"{var}__pop_weight_dedup")
        sx = float(xr.std())
        for c in wcols:
            dr = resid(f"{var}__{c}") - xr
            sd = float(dr.std())
            rows.append({"side": side, "weight": c, "rho_pop": rho[c],
                         "sd_X": sx, "sd_D": sd,
                         "D_share_pct": 100 * sd / sx,
                         "corr_X_D": float(np.corrcoef(xr, dr)[0, 1])
                         if sd > 0 else np.nan})
    r = pd.DataFrame(rows)
    r["theta80_pred"] = 2.80 / (r.side.map(T_BETA) * r.D_share_pct / 100)
    return r.sort_values(["side", "theta80_pred"])


# --------------------------------------------------------------------------
def family(w: str) -> str:
    if w.startswith("w_popA"):
        return "ambient population (WorldMove proxy)"
    if w.startswith("w_dens"):
        return "accessibility / density (15-min city proxy)"
    return "reference (already reported)"


def main() -> None:
    print(__doc__.split("OUTPUT")[0])
    w = candidate_weights()
    print(f"    {len(w)} cities, "
          f"{len([c for c in w.columns if c.startswith('w_')])} candidates\n")
    r = screen(w)
    r["family"] = r.weight.map(family)

    for side in ("cool", "heat"):
        s = r[r.side == side]
        print(f"\n[{side}]  {'weight':16s}{'family':46s}{'rho':>7s}"
              f"{'D/X %':>8s}{'theta80':>9s}")
        for x in s.itertuples():
            flag = "   <= usable" if x.theta80_pred <= 1 else ""
            print(f"      {x.weight:16s}{x.family:46s}{x.rho_pop:+7.2f}"
                  f"{x.D_share_pct:8.1f}{x.theta80_pred:9.2f}{flag}")

    TAB.mkdir(parents=True, exist_ok=True)
    r.to_csv(TAB / "TS18_external_weight_screen.csv", index=False)
    print(f"\n    wrote {TAB / 'TS18_external_weight_screen.csv'}")

    print("\nVERDICT")
    for fam in sorted(r.family.unique()):
        s = r[(r.family == fam)]
        best = s.loc[s.theta80_pred.idxmin()]
        verdict = ("worth fitting" if best.theta80_pred <= 1 else
                   f"cannot reject theta = 1; needs an effect "
                   f"{best.theta80_pred:.1f}x a full reweighting")
        print(f"    {fam:46s} best theta80 = {best.theta80_pred:5.2f} "
              f"({best.weight}, {best.side})  -> {verdict}")


if __name__ == "__main__":
    main()
