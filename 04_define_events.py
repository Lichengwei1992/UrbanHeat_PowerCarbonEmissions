def load_fua_lookup() -> pd.DataFrame:
    """
    Load the FUA city lookup table generated by 05d_extract_era5_cities.py.

    city_id is the zero-padded shapefile row index ("0000"…"1582"), matching
    the format used in ERA5/baseline/threshold_table_doy.parquet and
    outputs/city_climate_2019_2021.parquet.

    Returns DataFrame: city_id | city | country | fuacode | lat | lon
    """
    lookup_f = OUT_DIR.parent / "fua_city_lookup.csv"
    if not lookup_f.exists():
        raise FileNotFoundError(
            f"FUA lookup table not found:\n  {lookup_f}\n"
            "Run 05d_extract_era5_cities.py first."
        )
    lookup = pd.read_csv(lookup_f, dtype={"city_id": str})
    lookup["city_id"] = lookup["city_id"].str.zfill(4)
    print(f"  Loaded {len(lookup)} cities from fua_city_lookup.csv")
    return lookup


def build_city_id_map(fua_lookup: pd.DataFrame) -> pd.Series:
    """
    Build a mapping from normalised (city, country) string → city_id.

    Used to assign the canonical zero-padded city_id to Carbon Monitor rows,
    which identify cities by (city, country) name rather than shapefile index.

    Returns pd.Series indexed by 'city_country_key' → city_id.
    """
    df = fua_lookup.copy()
    df["key"] = df["city"].str.strip().str.lower() + "_" + \
                df["country"].str.strip().str.lower()
    # Drop duplicates (shouldn't exist but guard anyway)
    df = df.drop_duplicates("key")
    return df.set_index("key")["city_id"]


