# SECTION 4: Define extreme events
# ═════════════════════════════════════════════════════════════════════════════
def compute_thresholds(climate_df):
    """
    Load WMO 1991-2020 DOY-windowed percentile thresholds and join to climate_df.

    Thresholds are generated by 05c_download_era5_baseline.py:
        ERA5/baseline/threshold_table_doy.parquet
        Schema: city_id | doy | tmax_p90 | tmin_p10 | n_samples

    Each row in climate_df gets its own threshold based on (city_id, DOY),
    so a July heat event is evaluated against July climatology, not an annual mean.

    Falls back to a flat annual threshold computed from the 2019 study data if
    the pre-computed file does not exist (with a loud warning).

    Returns: climate_df with tmax_p90 and tmin_p10 columns added (row-specific).
    """
    print("\n[3] Loading city×DOY climate thresholds …")

    if not THRESHOLD_FILE.exists():
        print(f"\n  WARNING: WMO threshold file not found:\n    {THRESHOLD_FILE}")
        print("  Run 05c_download_era5_baseline.py first for proper DOY-windowed thresholds.")
        print("  FALLBACK: computing flat annual p90/p10 from 2019 study data (SUBOPTIMAL).\n")

        baseline = climate_df[climate_df['date'].dt.year == CARBON_BASELINE_YEAR].copy()
        flat = baseline.groupby('city_id').agg(
            tmax_p90=('tmax', lambda x: np.nanpercentile(x, HEAT_PERCENTILE)),
            tmin_p10=('tmin', lambda x: np.nanpercentile(x, COLD_PERCENTILE)),
        ).reset_index()

        # Broadcast the single threshold per city across all DOYs
        climate_df = climate_df.merge(flat, on='city_id', how='left')
        print(f"  [FALLBACK] Flat thresholds for {len(flat)} cities")
        print(f"  Tmax p90 range: {flat['tmax_p90'].min():.1f}°C – {flat['tmax_p90'].max():.1f}°C")
        print(f"  Tmin p10 range: {flat['tmin_p10'].min():.1f}°C – {flat['tmin_p10'].max():.1f}°C")
        return climate_df

    # ── Load pre-computed WMO thresholds ──────────────────────────────────────
    thresholds_doy = pd.read_parquet(THRESHOLD_FILE)
    print(f"  Loaded {len(thresholds_doy):,} city×DOY thresholds "
          f"({thresholds_doy['city_id'].nunique()} cities × "
          f"{thresholds_doy['doy'].nunique()} DOYs)")

    # Add DOY to climate data and join thresholds row-by-row
    climate_df = climate_df.copy()
    climate_df['doy'] = climate_df['date'].dt.dayofyear

    # DOY 366 (Feb 29 in leap years): map to DOY 60 thresholds as closest match
    climate_df.loc[climate_df['doy'] == 366, 'doy'] = 60

    climate_df = climate_df.merge(
        thresholds_doy[['city_id', 'doy', 'tmax_p90', 'tmin_p10']],
        on=['city_id', 'doy'],
        how='left',
    )

    n_missing = climate_df['tmax_p90'].isna().sum()
    if n_missing > 0:
        print(f"  Warning: {n_missing} rows have no threshold match — check city_id alignment")

    print(f"  Tmax p90 range: {climate_df['tmax_p90'].min():.1f}°C – "
          f"{climate_df['tmax_p90'].max():.1f}°C")
    print(f"  Tmin p10 range: {climate_df['tmin_p10'].min():.1f}°C – "
          f"{climate_df['tmin_p10'].max():.1f}°C")
    print(f"  Median samples per city×DOY: "
          f"{thresholds_doy['n_samples'].median():.0f}")

    return climate_df


def flag_consecutive_events(series, threshold, min_days, above=True):
    """
    Flag events as sequences of ≥min_days consecutive days where condition is met.

    Parameters
    ----------
    series    : pd.Series  — observed values (e.g. daily Tmax)
    threshold : scalar or pd.Series — exceedance threshold.
                Pass a Series for DOY-specific thresholds (one per row).
                Pass a scalar for a city-level fixed threshold.
    min_days  : int  — minimum consecutive exceedance days to count as an event
    above     : bool — True = above threshold (heatwave); False = below (cold wave)

    Returns: event_flag (int array), event_id (int array), days_in_event (int array)
    """
    if above:
        exceedance = series > threshold
    else:
        exceedance = series < threshold

    n = len(series)
    event_flag = np.zeros(n, dtype=int)
    event_id   = np.zeros(n, dtype=int)
    days_in    = np.zeros(n, dtype=int)

    # Find runs of consecutive True values
    eid = 0
    i = 0
    while i < n:
        if exceedance.iloc[i]:
            j = i
            while j < n and exceedance.iloc[j]:
                j += 1
            run_len = j - i
            if run_len >= min_days:
                eid += 1
                for k in range(i, j):
                    event_flag[k] = 1
                    event_id[k]   = eid
                    days_in[k]    = k - i + 1
            i = j
        else:
            i += 1

    return event_flag, event_id, days_in


def define_events(climate_df, thresholds=None):
    """
    Apply event definitions to each city's time series.

    climate_df must already contain tmax_p90 and tmin_p10 columns joined
    per (city_id, DOY) by compute_thresholds(). The `thresholds` argument
    is retained for backwards compatibility but is no longer used.

    Returns DataFrame with event flags and metadata.
    """
    print("\n[4] Defining extreme events per city …")

    # thresholds are already joined row-by-row in climate_df by compute_thresholds()
    climate_df = climate_df.sort_values(['city_id', 'date']).reset_index(drop=True)

    result_parts = []

    for city_id, grp in climate_df.groupby('city_id'):
        grp = grp.sort_values('date').copy()

        # DOY-specific threshold series (one value per day, aligned to calendar date)
        tmax_thresh = grp['tmax_p90'].reset_index(drop=True)   # pd.Series
        tmin_thresh = grp['tmin_p10'].reset_index(drop=True)   # pd.Series

        # ── Heatwave: Tmax > DOY-specific p90 for ≥3 consecutive days
        hw_flag, hw_id, hw_days = flag_consecutive_events(
            grp['tmax'].reset_index(drop=True), tmax_thresh, HEAT_DURATION, above=True)

        # ── Cold wave: Tmin < DOY-specific p10 for ≥3 consecutive days
        cw_flag, cw_id, cw_days = flag_consecutive_events(
            grp['tmin'].reset_index(drop=True), tmin_thresh, COLD_DURATION, above=False)

        # ── Extreme precip: precip > p95 for ≥1 day
        # precip_p95 is still a city-level scalar (no DOY variation needed for precip)
        prec_thresh = grp['precip_p95'].iloc[0] if 'precip_p95' in grp.columns else np.nan
        rn_flag, rn_id, rn_days = flag_consecutive_events(
            grp['precip_mm'].reset_index(drop=True), prec_thresh, RAIN_DURATION, above=True)

        grp['heat_event']        = hw_flag
        grp['heat_event_id']     = hw_id
        grp['heat_day_n']        = hw_days
        grp['cold_event']        = cw_flag
        grp['cold_event_id']     = cw_id
        grp['cold_day_n']        = cw_days
        grp['rain_event']        = rn_flag
        grp['rain_event_id']     = rn_id
        grp['rain_day_n']        = rn_days

        # Combined extreme day flag
        grp['any_extreme']       = (grp['heat_event'] | grp['cold_event'] | grp['rain_event']).astype(int)

        # Days since most recent extreme event (for lagged effects)
        grp['days_since_heat']   = _days_since_event(grp['heat_event'].values)
        grp['days_since_cold']   = _days_since_event(grp['cold_event'].values)
        grp['days_since_rain']   = _days_since_event(grp['rain_event'].values)

        result_parts.append(grp)

    events_df = pd.concat(result_parts, ignore_index=True)

    # Summary
    n_cities   = events_df['city_id'].nunique()
    n_heat_ev  = events_df.groupby('city_id')['heat_event_id'].max().sum()
    n_cold_ev  = events_df.groupby('city_id')['cold_event_id'].max().sum()
    n_rain_ev  = events_df.groupby('city_id')['rain_event_id'].max().sum()

    print(f"  Cities: {n_cities}")
    print(f"  Total heatwave events identified:     {n_heat_ev:,}")
    print(f"  Total cold wave events identified:    {n_cold_ev:,}")
    print(f"  Total extreme rain events identified: {n_rain_ev:,}")

    # Heat-day fraction
    heat_frac = events_df['heat_event'].mean() * 100
    cold_frac = events_df['cold_event'].mean() * 100
    rain_frac = events_df['rain_event'].mean() * 100
    print(f"  % city-days flagged — heat: {heat_frac:.1f}%  cold: {cold_frac:.1f}%  rain: {rain_frac:.1f}%")

    return events_df


def _days_since_event(flag_array):
    """Count days since last event day (0 on event days, incrementing after)."""
    result = np.full(len(flag_array), np.nan)
    counter = np.nan
    for i, f in enumerate(flag_array):
        if f == 1:
            counter = 0
        elif not np.isnan(counter):
            counter += 1
        result[i] = counter
    return result


