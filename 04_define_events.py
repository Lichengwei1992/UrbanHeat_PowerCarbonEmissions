# SECTION 7: Event summary statistics
# ═════════════════════════════════════════════════════════════════════════════
def summarise_events(panel):
    """Generate event summary table per city."""
    print("\n[6] Generating event summary …")

    event_cols = {
        'heat': ('heat_event', 'heat_event_id'),
        'cold': ('cold_event', 'cold_event_id'),
        'rain': ('rain_event', 'rain_event_id'),
    }

    parts = []
    for etype, (flag_col, id_col) in event_cols.items():
        if flag_col not in panel.columns:
            continue
        grp = panel.groupby('city_id').agg(
            n_event_days = (flag_col, 'sum'),
            n_events     = (id_col,   'max'),
        ).reset_index()
        grp['event_type'] = etype
        parts.append(grp)

    if not parts:
        return pd.DataFrame()

    summary = pd.concat(parts, ignore_index=True)

    # Pivot for readability
    wide = summary.pivot(index='city_id', columns='event_type',
                         values=['n_event_days', 'n_events'])
    wide.columns = [f"{b}_{a}" for a, b in wide.columns]
    wide = wide.reset_index()

    print(wide.describe().round(1).to_string())
    return wide


