"""
04_define_events.py
===================
Define extreme climate events from ERA5 data and build the city × day
analysis panel by merging Carbon Monitor Cities emissions with climate
indicators, event flags, and OxCGRT stringency.

Event types:
  1. Heatwaves   — city-specific 90th-pct Tmax, ≥3 consecutive days
  2. Cold waves  — city-specific 10th-pct Tmin, ≥3 consecutive days
  3. Extreme precip — city-specific 95th-pct daily precip, ≥1 day

Run after:
  01_data_audit.py      (Carbon Monitor profiling)
  02_acquire_data.py    (ERA5 download, OxCGRT download)
  03_build_city_shapefiles.py  (city centroids + FUA polygons)

Outputs → outputs/04_events/
  city_climate_daily.parquet    — city × day climate variables
  event_flags.parquet           — city × day event indicators
  panel_city_daily.parquet      — FULL merged analysis panel
  event_summary.csv             — count of events per city/type
  threshold_table.csv           — per-city climate thresholds

Requirements:
  pip install pandas numpy xarray netcdf4 scipy pytz timezonefinder
"""

