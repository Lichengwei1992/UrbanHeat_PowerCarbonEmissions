# SECTION 6: Build and save the analysis panel
# ═════════════════════════════════════════════════════════════════════════════
def build_panel(emissions_df, events_df, oxcgrt_df=None, utci_df=None, coords_df=None):
    """
    Merge all components into the master analysis panel.

    Panel structure: city_id × date (1 row per city per day)
    """
    print("\n[5] Building master analysis panel …")

    # Start from emissions
    panel = emissions_df.copy()

    # Merge climate + events (left join to keep all emission dates)
    climate_cols = ['city_id', 'date', 'tmax', 'tmin', 'tmean', 'precip_mm',
                    'tmax_p90', 'tmin_p10', 'precip_p95',
                    'heat_event', 'heat_event_id', 'heat_day_n',
                    'cold_event', 'cold_event_id', 'cold_day_n',
                    'rain_event', 'rain_event_id', 'rain_day_n',
                    'any_extreme', 'days_since_heat', 'days_since_cold', 'days_since_rain']
    avail_cols = [c for c in climate_cols if c in events_df.columns]

    if len(events_df) > 0:
        panel = panel.merge(events_df[avail_cols], on=['city_id', 'date'], how='left')
        print(f"  After climate merge: {len(panel):,} rows")

    # Add ISO3 country code for OxCGRT join (from FUA lookup)
    if coords_df is not None and 'iso3' in coords_df.columns:
        panel = panel.merge(coords_df[['city_id', 'iso3']], on='city_id', how='left')
    elif coords_df is not None and 'country' in coords_df.columns:
        # iso3 not in FUA shapefile — use 2-letter country code as fallback
        panel = panel.merge(coords_df[['city_id', 'country']].rename(
            columns={'country': 'country_name'}), on='city_id', how='left')

    # OxCGRT join on country_code × date
    if oxcgrt_df is not None:
        join_col = 'iso3' if 'iso3' in panel.columns else 'country_code'
        if join_col in panel.columns:
            panel = panel.merge(
                oxcgrt_df.rename(columns={'country_code': join_col}),
                on=[join_col, 'date'], how='left'
            )
            print(f"  After OxCGRT merge: {len(panel):,} rows")

    # UTCI join on city_id × date
    if utci_df is not None:
        panel = panel.merge(utci_df[['city_id', 'date', 'utci_mean', 'utci_max']],
                            on=['city_id', 'date'], how='left')
        print(f"  After UTCI merge: {len(panel):,} rows")

    # ── Add temporal features for fixed-effects regression ──
    panel['year']        = panel['date'].dt.year
    panel['month']       = panel['date'].dt.month
    panel['week_of_year']= panel['date'].dt.isocalendar().week.astype(int)
    panel['day_of_week'] = panel['date'].dt.dayofweek   # 0=Mon, 6=Sun
    panel['is_weekend']  = (panel['day_of_week'] >= 5).astype(int)
    panel['yw_fe']       = panel['year'].astype(str) + "_w" + \
                           panel['week_of_year'].astype(str).str.zfill(2)  # year×week FE key

    # ── Emission anomaly: deviation from 2019 seasonal baseline ──
    # Compute city × week-of-year mean from 2019 baseline
    baseline_2019 = panel[panel['year'] == 2019].copy()
    if len(baseline_2019) > 0:
        wk_mean = baseline_2019.groupby(['city_id', 'week_of_year'])['co2_total'].mean().rename('co2_baseline')
        panel = panel.merge(wk_mean, on=['city_id', 'week_of_year'], how='left')
        panel['co2_anomaly']     = panel['co2_total'] - panel['co2_baseline']
        panel['co2_anomaly_pct'] = panel['co2_anomaly'] / panel['co2_baseline'] * 100
        print("  ✓ Emission anomaly computed (vs. 2019 week-of-year baseline)")

    # ── Log emissions for regression ──
    for col in ['co2_total'] + [c for c in panel.columns if c.startswith('co2_') and c not in
                                 ('co2_total','co2_baseline','co2_anomaly','co2_anomaly_pct')]:
        if col in panel.columns and panel[col].gt(0).any():
            panel[f'ln_{col}'] = np.log(panel[col].clip(lower=0.001))

    # ── Temperature anomaly (vs. city-specific baseline mean) ──
    if 'tmax' in panel.columns:
        city_tmean = baseline_2019.groupby('city_id')['tmax'].mean().rename('tmax_city_mean')
        panel = panel.merge(city_tmean, on='city_id', how='left')
        panel['tmax_anomaly'] = panel['tmax'] - panel['tmax_city_mean']

    # Sort
    panel = panel.sort_values(['city_id', 'date']).reset_index(drop=True)

    print(f"\n  Panel shape: {panel.shape}")
    print(f"  Cities: {panel['city_id'].nunique()}")
    print(f"  Date range: {panel['date'].min().date()} → {panel['date'].max().date()}")
    print(f"  Columns: {list(panel.columns)}")

    return panel


