# SECTION 3: Load pre-extracted ERA5 city climate
# ═════════════════════════════════════════════════════════════════════════════
def load_era5_city_daily() -> pd.DataFrame:
    """
    Load the pre-extracted city-level ERA5 climate parquet produced by
    05d_extract_era5_cities.py.

    city_id in this file uses the zero-padded FUA shapefile index, matching
    the WMO threshold table exactly — no remapping needed here.

    Returns DataFrame: city_id | date | tmax | tmin | tmean | utci_mean | utci_max
    """
    climate_f = OUT_DIR.parent / "city_climate_2019_2021.parquet"
    if not climate_f.exists():
        raise FileNotFoundError(
            f"Pre-extracted climate file not found:\n  {climate_f}\n"
            "Run 05d_extract_era5_cities.py first."
        )

    climate = pd.read_parquet(climate_f, dtype_backend="numpy_nullable")
    climate["city_id"] = climate["city_id"].astype(str).str.zfill(4)
    climate["date"]    = pd.to_datetime(climate["date"])
    climate = climate[
        (climate["date"] >= STUDY_START) & (climate["date"] <= STUDY_END)
    ].copy()

    # Ensure expected columns exist
    for col in ("tmax", "tmin", "tmean"):
        if col not in climate.columns:
            climate[col] = np.nan
    if "precip_mm" not in climate.columns:
        climate["precip_mm"] = np.nan   # precipitation not in ERA5 temp files

    print(f"  ✓ ERA5 climate loaded: {len(climate):,} city-day records  "
          f"| cities: {climate['city_id'].nunique()}"
          f"| date range: {climate['date'].min().date()} → {climate['date'].max().date()}")
    return climate


