# SECTION 2: Load Carbon Monitor Cities emissions
# ═════════════════════════════════════════════════════════════════════════════
def load_carbon_monitor():
    """
    Load Carbon Monitor Cities data.

    Preferred source: the all-cities-FUA global file
    (carbon-monitor-cities-all-cities-FUA-v*.csv, ~563 MB).
    Fallback: concatenate all per-country CSVs.

    Columns in v0325 files:
        city | country | date | sector | value (KtCO2 per day) | timestamp
    """
    print("\n[1] Loading Carbon Monitor Cities data …")

    # Prefer the all-cities FUA global file (explicit pattern to avoid
    # accidentally matching single-country files like Vietnam-v0325.csv)
    global_files = sorted(DATA_DIR.glob("*all-cities*FUA*.csv")) + \
                   sorted(DATA_DIR.glob("*all-cities*.csv"))

    if global_files:
        f = global_files[0]
        df = pd.read_csv(f, encoding='utf-8-sig')
        print(f"  Loaded global file: {f.name} ({len(df):,} rows)")
    else:
        # Fallback: concatenate per-country files, skip the US-Counties file
        # (county-level, not FUA-matched) and skip if name matches 'all-cities'
        country_files = [
            f for f in sorted(DATA_DIR.glob("*.csv"))
            if "all-cities" not in f.name.lower()
            and "US-Counties" not in f.name
        ]
        parts = []
        for f in country_files:
            try:
                parts.append(pd.read_csv(f, encoding='utf-8-sig'))
            except Exception as e:
                print(f"  Warning: could not read {f.name}: {e}")
        if not parts:
            raise FileNotFoundError(f"No Carbon Monitor CSV files found in {DATA_DIR}")
        df = pd.concat(parts, ignore_index=True)
        print(f"  Concatenated {len(country_files)} country files: {len(df):,} rows")

    # ── Standardise column names (first-match wins to avoid duplicates) ───
    # v0325 columns: city | country | date | sector | value (KtCO2 per day) | timestamp
    # Note: 'timestamp' is a Unix epoch duplicate of 'date' — skip it.
    col_map = {}
    mapped = set()

    DATE_NAMES  = {'date'}                    # 'timestamp' excluded intentionally
    CITY_NAMES  = {'city', 'city_name', 'cityname'}
    CTR_NAMES   = {'country', 'country_name', 'countryname'}
    SEC_NAMES   = {'sector', 'sector_name'}
    CO2_NAMES   = {'co2', 'co2_kt', 'emission', 'emissions', 'mtco2'}

    for c in df.columns:
        cl = c.lower().strip()
        if cl in DATE_NAMES and 'date' not in mapped:
            col_map[c] = 'date';    mapped.add('date')
        elif cl in CITY_NAMES and 'city' not in mapped:
            col_map[c] = 'city';    mapped.add('city')
        elif cl in CTR_NAMES and 'country' not in mapped:
            col_map[c] = 'country'; mapped.add('country')
        elif cl in SEC_NAMES and 'sector' not in mapped:
            col_map[c] = 'sector';  mapped.add('sector')
        elif (cl in CO2_NAMES or cl.startswith('value')) and 'co2_kt' not in mapped:
            col_map[c] = 'co2_kt';  mapped.add('co2_kt')

    df = df.rename(columns=col_map)

    # Drop any residual duplicate columns (e.g. original 'timestamp' kept as-is)
    df = df.loc[:, ~df.columns.duplicated()]

    # ── Parse date ────────────────────────────────────────────────────────
    if 'date' not in df.columns:
        raise ValueError(f"No 'date' column found after rename. Columns: {list(df.columns)}")

    df['date'] = pd.to_datetime(df['date'], dayfirst=False, errors='coerce')
    df = df.dropna(subset=['date'])
    df = df[(df['date'] >= STUDY_START) & (df['date'] <= STUDY_END)]

    # Drop rows with missing city (some files have country-level totals)
    if 'city' in df.columns:
        df = df.dropna(subset=['city'])
        df = df[df['city'].str.strip() != '']

    # ── Pivot to wide: one row per city × date, one column per sector ─────
    df['city_id'] = df['city'].str.strip().str.lower() + "_" + \
                    df['country'].str.strip().str.lower()

    if 'sector' in df.columns and 'co2_kt' in df.columns:
        sectors = sorted(df['sector'].dropna().unique())
        print(f"  Sectors: {sectors}")
        wide = df.pivot_table(
            index=['city_id', 'city', 'country', 'date'],
            columns='sector',
            values='co2_kt',
            aggfunc='sum'
        ).reset_index()
        wide.columns.name = None
        sector_cols = [c for c in wide.columns
                       if c not in ('city_id', 'city', 'country', 'date')]
        wide['co2_total'] = wide[sector_cols].sum(axis=1, skipna=True)
    else:
        wide = df.copy()
        wide['co2_total'] = wide.get('co2_kt', np.nan)

    print(f"  Study period rows: {len(wide):,}  |  cities: {wide['city_id'].nunique()}")
    return wide


def remap_carbon_city_ids(emissions_df: pd.DataFrame,
                          city_id_map: pd.Series) -> pd.DataFrame:
    """
    Replace the name-based city_id in Carbon Monitor data with the canonical
    zero-padded FUA shapefile index, so it can join against the ERA5 climate
    data and WMO threshold table.

    The name-based key is: city.lower() + "_" + country.lower()
    Carbon Monitor city names match FUA shapefile city names (the shapefile was
    built to match the 1,583 Carbon Monitor cities exactly).

    Rows with no match (city name mismatch) are printed as warnings and kept
    with their original name-based city_id — they will not get ERA5 thresholds.
    """
    df = emissions_df.copy()
    key = df["city"].str.strip().str.lower() + "_" + \
          df["country"].str.strip().str.lower()
    mapped = key.map(city_id_map)

    n_miss = mapped.isna().sum()
    n_unique_miss = key[mapped.isna()].nunique()
    if n_miss > 0:
        miss_cities = key[mapped.isna()].unique()[:10]
        print(f"  Warning: {n_unique_miss} Carbon Monitor cities have no FUA match "
              f"({n_miss:,} rows). Examples: {list(miss_cities)}")
        print("  These rows will be kept but will lack ERA5 climate data.")
        # Fall back to name-based id for unmatched rows
        mapped = mapped.fillna(key)

    df["city_id"] = mapped
    matched = (mapped == key).sum()
    print(f"  city_id remapped: {len(df) - matched:,} / {len(df):,} rows "
          f"now use FUA shapefile index")
    return df


